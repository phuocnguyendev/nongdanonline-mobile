class CarePackage {
    constructor(id, image, name, description, price, timeUse, kindOfAnimal ) {
        this.id = id;
        this.image = image;
        this.name = name;
        this.description = description;
        this.price = price;
        this.timeUse = timeUse;
        this.kindOfAnimal = kindOfAnimal;
    }
}

export default CarePackage;
